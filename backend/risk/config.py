"""Risk configuration (Bot 3 private model - not a shared contract).

Everything is expressed with the shared contract sub-models (`PositionRiskRules`, `ExitRules`) where one
exists, plus a handful of portfolio-level limits that have no contract field yet.
Percentages are percent units (2.5 == 2.5%), like the contracts.
"""
from __future__ import annotations

import os
from typing import Optional

from pydantic import BaseModel, ConfigDict, Field

from backend.contracts import ActivationMode, ExitRules, ManualStrategy, PositionRiskRules

from .live import LiveRiskProfile, env_true


class SymbolRiskRules(BaseModel):
    """Per-symbol override (e.g. taken from an active ManualStrategy). Unset fields fall back to RiskConfig."""

    model_config = ConfigDict(extra="forbid")

    position_rules: Optional[PositionRiskRules] = None
    exit_rules: Optional[ExitRules] = None
    activation: Optional[ActivationMode] = None

    @classmethod
    def from_manual_strategy(cls, strategy: ManualStrategy) -> "SymbolRiskRules":
        return cls(position_rules=strategy.risk, exit_rules=strategy.exit, activation=strategy.activation)


class RiskConfig(BaseModel):
    """Static limits for DefaultRiskManager. Defaults are conservative and mirror the reference simulator where it has
    an equivalent (size 15%, cooldown 5 bars, TP 12%, SL 6%, trailing 4% off by default). Max open positions defaults to
    ``default_max_open_positions`` (3) whenever the PositionRiskRules in force did not set it explicitly."""

    model_config = ConfigDict(extra="forbid")

    position_rules: PositionRiskRules = Field(default_factory=PositionRiskRules)
    exit_rules: ExitRules = Field(default_factory=ExitRules)
    symbol_rules: dict[str, SymbolRiskRules] = Field(default_factory=dict)

    max_total_exposure_pct: float = Field(default=60.0, gt=0, le=100, description="Sum of open positions + new order, % of equity")
    max_token_exposure_pct: float = Field(default=30.0, gt=0, le=100, description="Per-symbol exposure incl. new order, % of equity")
    daily_loss_limit_pct: Optional[float] = Field(
        default=5.0, gt=0, description="Block new entries once Portfolio.daily_pnl <= -X% of starting_capital. None = off")
    max_trades_per_day: Optional[int] = Field(default=None, ge=1, description="Block new entries once trades_today >= N")
    min_order_notional: float = Field(default=10.0, ge=0, description="Orders below this USDT amount are blocked")
    default_max_open_positions: int = Field(default=3, ge=1, description=(
        "Used when the PositionRiskRules in force (RiskConfig.position_rules or a symbol/ManualStrategy override) did not "
        "set max_open_positions explicitly - the contract model's own default (1) is ignored by risk"))

    allow_live: bool = Field(default=False, description="LIVE BUYs are blocked unless explicitly enabled here")
    live: LiveRiskProfile = Field(default_factory=LiveRiskProfile, description="Extra limits applied automatically in LIVE")
    allow_exits_when_paused: bool = Field(default=True, description="Protective SELLs still pass while paused")
    risk_exits_bypass_confirmation: bool = Field(
        default=True, description="SELLs generated by check_exits (SL/TP/trailing/max-loss/emergency) never wait for the user")

    @classmethod
    def from_env(cls, **overrides) -> "RiskConfig":
        """Defaults + env. ``allow_live`` is True only if RISK_ALLOW_LIVE, LIVE_TRADING_ENABLED and BINANCE_LIVE_ENABLED
        are all exactly "true". Optional numeric overrides of the LIVE profile:
        RISK_LIVE_MAX_ORDER_USDT, RISK_LIVE_MAX_DAILY_LOSS_USDT, RISK_LIVE_MAX_DAILY_NOTIONAL_USDT,
        RISK_LIVE_MAX_EXPOSURE_USDT, RISK_LIVE_MAX_TOKEN_EXPOSURE_USDT, RISK_LIVE_MAX_DATA_AGE_S, RISK_LIVE_MAX_SLIPPAGE_PCT, RISK_LIVE_MAX_FAVORABLE_IMPACT_PCT,
        RISK_LIVE_FEE_BUFFER_USDT, RISK_LIVE_MIN_BNB; RISK_LIVE_MARKET_HOURS=false disables the market-hours guard. No secrets are read."""
        allow = all(env_true(k) for k in ("RISK_ALLOW_LIVE", "LIVE_TRADING_ENABLED", "BINANCE_LIVE_ENABLED"))
        live: dict = {}
        for env, field in (("RISK_LIVE_MAX_ORDER_USDT", "max_order_notional_usdt"),
                           ("RISK_LIVE_MAX_DAILY_LOSS_USDT", "max_daily_loss_usdt"),
                           ("RISK_LIVE_MAX_DAILY_NOTIONAL_USDT", "max_daily_notional_usdt"),
                           ("RISK_LIVE_MAX_EXPOSURE_USDT", "max_open_exposure_usdt"),
                           ("RISK_LIVE_MAX_TOKEN_EXPOSURE_USDT", "max_token_exposure_usdt"),
                           ("RISK_LIVE_MAX_DATA_AGE_S", "max_data_age_seconds"),
                           ("RISK_LIVE_MAX_SLIPPAGE_PCT", "max_slippage_pct"),
                           ("RISK_LIVE_MAX_FAVORABLE_IMPACT_PCT", "max_favorable_impact_pct"),
                           ("RISK_LIVE_FEE_BUFFER_USDT", "fee_buffer_usdt"),
                           ("RISK_LIVE_MIN_BNB", "min_gas_reserve")):
            v = os.getenv(env, "").strip()
            if v:
                live[field] = float(v)
        mh = os.getenv("RISK_LIVE_MARKET_HOURS", "").strip().lower()
        if mh in ("true", "false"):
            live["market_hours_enabled"] = mh == "true"
        data = {"allow_live": allow, "live": LiveRiskProfile(**live)}
        data.update(overrides)
        return cls(**data)

    def rules_for(self, symbol: str) -> tuple[PositionRiskRules, ExitRules, Optional[ActivationMode]]:
        """Rules in force for ``symbol``. If the chosen PositionRiskRules never set ``max_open_positions`` explicitly
        (pydantic ``model_fields_set``), it is replaced with ``default_max_open_positions``."""
        o = self.symbol_rules.get(symbol)
        if o is None:
            prules, erules, act = self.position_rules, self.exit_rules, None
        else:
            prules, erules, act = o.position_rules or self.position_rules, o.exit_rules or self.exit_rules, o.activation
        if "max_open_positions" not in prules.model_fields_set:
            prules = prules.model_copy(update={"max_open_positions": self.default_max_open_positions})
        return prules, erules, act
