#!/usr/bin/env python3
"""Generate contracts/schema/*.json and frontend/src/contracts.ts from backend/contracts.

Usage:  python scripts/gen_contracts.py          # write files
        python scripts/gen_contracts.py --check  # exit 1 if files are stale (used by tests/CI)
"""
from __future__ import annotations

import json
import sys
from enum import Enum
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from pydantic.json_schema import models_json_schema  # noqa: E402

from backend.contracts import enums as enums_mod  # noqa: E402
from backend.contracts.models import ALL_MODELS, CONTRACTS_VERSION, DEFAULT_INITIAL_CAPITAL, QUOTE_TTL_SECONDS, SIM_WARMUP_BARS  # noqa: E402

SCHEMA_DIR = ROOT / "contracts" / "schema"
TS_FILE = ROOT / "frontend" / "src" / "contracts.ts"


def ts_type(s: dict) -> str:
    if "$ref" in s:
        return s["$ref"].split("/")[-1]
    if "const" in s:
        return json.dumps(s["const"])
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    for key in ("anyOf", "oneOf"):
        if key in s:
            parts = []
            for sub in s[key]:
                t = ts_type(sub)
                if t not in parts:
                    parts.append(t)
            return " | ".join(parts)
    if "allOf" in s and len(s["allOf"]) == 1:
        return ts_type(s["allOf"][0])
    t = s.get("type")
    if t == "string":
        return "string"
    if t in ("number", "integer"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        inner = ts_type(s.get("items", {}))
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if t == "object":
        ap = s.get("additionalProperties")
        if isinstance(ap, dict) and ap:
            return f"Record<string, {ts_type(ap)}>"
        return "Record<string, unknown>"
    return "unknown"


def build_defs() -> dict:
    _, top = models_json_schema([(m, "validation") for m in ALL_MODELS], ref_template="#/$defs/{model}")
    return top["$defs"]


def render_ts(defs: dict) -> str:
    out = [
        "// AUTO-GENERATED by scripts/gen_contracts.py from backend/contracts. DO NOT EDIT BY HAND.",
        "// Change backend/contracts/*.py (coordinator only) and re-run: python scripts/gen_contracts.py",
        "/* eslint-disable */",
        "",
        f'export const CONTRACTS_VERSION = "{CONTRACTS_VERSION}";',
        f"export const QUOTE_TTL_SECONDS = {QUOTE_TTL_SECONDS};",
        f"export const SIM_WARMUP_BARS = {SIM_WARMUP_BARS};",
        f"export const DEFAULT_INITIAL_CAPITAL = {DEFAULT_INITIAL_CAPITAL:g};",
        "",
        "// ---------- enums",
    ]
    enum_classes = [v for v in vars(enums_mod).values() if isinstance(v, type) and issubclass(v, Enum) and v.__module__ == enums_mod.__name__]
    for e in enum_classes:
        vals = [m.value for m in e]
        out.append(f"export type {e.__name__} = {' | '.join(json.dumps(v) for v in vals)};")
        out.append(f"export const {e.__name__}Values = {json.dumps(vals)} as const;")
        out.append("")
    out.append("// ---------- models (optional `?` = has a backend default; responses always include it)")
    enum_names = {e.__name__ for e in enum_classes}
    for name in [m.__name__ for m in ALL_MODELS]:
        d = defs[name]
        req = set(d.get("required", []))
        if d.get("description"):
            out.append(f"/** {d['description'].strip().splitlines()[0]} */")
        out.append(f"export interface {name} {{")
        for fname, fs in d.get("properties", {}).items():
            opt = "" if fname in req else "?"
            doc = f"  /** {fs['description']} */\n" if fs.get("description") else ""
            out.append(f"{doc}  {fname}{opt}: {ts_type(fs)};")
        out.append("}")
        out.append("")
    missing = set(defs) - enum_names - {m.__name__ for m in ALL_MODELS}
    if missing:
        raise SystemExit(f"schema defs not exported to TS (add to ALL_MODELS or enums): {sorted(missing)}")
    out.append("export type Token = TokenInfo;")
    return "\n".join(out) + "\n"


def render_schemas(defs: dict) -> dict[str, str]:
    files = {}
    for m in ALL_MODELS:
        files[f"{m.__name__}.json"] = json.dumps(m.model_json_schema(mode="validation"), indent=2, sort_keys=True) + "\n"
    files["_all.json"] = json.dumps({"version": CONTRACTS_VERSION, "$defs": defs}, indent=2, sort_keys=True) + "\n"
    return files


def main() -> int:
    check = "--check" in sys.argv
    defs = build_defs()
    targets = {SCHEMA_DIR / k: v for k, v in render_schemas(defs).items()}
    targets[TS_FILE] = render_ts(defs)
    stale = [p for p, content in targets.items() if not p.exists() or p.read_text() != content]
    if check:
        extra = [p for p in SCHEMA_DIR.glob("*.json") if p not in targets] if SCHEMA_DIR.exists() else []
        if stale or extra:
            print("Stale generated contract files:", *[str(p.relative_to(ROOT)) for p in stale + extra], sep="\n  ")
            print("Run: python scripts/gen_contracts.py")
            return 1
        print("contracts up to date")
        return 0
    SCHEMA_DIR.mkdir(parents=True, exist_ok=True)
    TS_FILE.parent.mkdir(parents=True, exist_ok=True)
    for p in SCHEMA_DIR.glob("*.json"):
        if p not in targets:
            p.unlink()
    for p, content in targets.items():
        p.write_text(content)
    print(f"wrote {len(targets) - 1} schema files + {TS_FILE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
